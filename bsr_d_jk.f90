!======================================================================
!   This routine creates the dipole input files used by RMT in jK coupling,
!   using the RMI format.
!======================================================================
!
!   INPUT FILES:
!
!      The inputs for this routine include BSR's target, cfg.nnn and rsol.nnn
!      files, and also the H file generated by bsr_H_jk.
!
!   OUTPUT FILES:
!
!      D00 lists the pairs of symmetry blocks that can be connected by dipole
!      transitions. A separate file is created for each of these pairs (D001,
!      D002, etc.) which contains reduced length and velocity dipole matrix
!      elements and the corresponding outer-region coefficients.
!
!      bsr_d_jk_Aug2026_candidate.log
!
!   NOTES:
!
!      The routine calls the BSR programs mult3 and bsr_dmat3 to calculate
!      dipole matrices between inner-region R-matrix eigenstates.
!
!   USAGE:
!
!      bsr_d_jk bin=../../deps klsp1=1 klsp2=2 ipar0=-1
!======================================================================

      Program bsr_d_jk

      Use target
      Use channels

      Implicit real(8) (A-H,O-Z)

      Integer :: nut=1
      Character(1)   :: slash = '/'
      Character(256) :: AF, AS, BI, BJ, FDD, FRAW, BIN_DIR
      Character(256) :: MULT_EXE, DMAT_EXE
      Real(8), allocatable :: CF(:,:,:)
      Real(8), allocatable :: TDL(:), TDV(:)
      Integer, allocatable :: L2P(:)
      Integer :: rank2,h_nelc,h_nz,h_nast

      Integer, external :: Icheck_file, ITRA

! ... short instructions:

      Call get_command_argument(1,AF)
      if(AF.eq.'?') then
       write(*,'(/a)') 'bsr_d_jk produces the dipole input files for RMT in jK coupling. These files use the'
       write(*,'(a)') 'RMI format.'
       write(*,'(/a)') 'Example: bsr_d_jk bin=../../deps klsp1=1 klsp2=2 ipar0=-1'
       write(*,'(/a)') 'INPUT:    target, H, cfg.nnn, rsol.nnn'
       write(*,'(a)')  'OUTPUT:   D00, D001, D002, ...'
       write(*,'(/a)') 'The directory containing mult3 and bsr_dmat3 can be specified through the "bin=..."'
       write(*,'(a)') 'assignment. For example, bin=../../BIN is appropriate if both files live in'
       write(*,'(a)') '../../BIN. If "bin=..." is left out, the shell checks PATH for the files.'
       write(*,'(/a)') 'klsp1 and klsp2 are the first and last partial waves the routine considers. By'
       write(*,'(a)') 'default the routine will treat all partial waves indicated in the BSR target file. As'
       write(*,'(a)') 'an example, klsp1=2 klsp2=5 considers partial waves 2 through 5. Another parameter'
       write(*,'(a)') 'klsp can be used. Selecting klsp=5 alone would include partial waves 1 through 5.'
       write(*,'(/a)') 'The parameter ipar0 selects which parity appears first in each pair of symmetry'
       write(*,'(a)') 'blocks. ipar0=+1 (even) is the default, while ipar0=-1 indicates that the odd-parity'
       write(*,'(a)') 'block comes first, as is the case in the carbon examples.'
       write(*,*)
       Stop
      end if

      BIN_DIR = ''
      Call Read_aarg('bin',BIN_DIR)
      if(len_trim(BIN_DIR).gt.0) then
       if(BIN_DIR(len_trim(BIN_DIR):len_trim(BIN_DIR)).ne.slash) &
        BIN_DIR = trim(BIN_DIR)//slash
      end if
      MULT_EXE = trim(BIN_DIR)//'mult3'
      DMAT_EXE = trim(BIN_DIR)//'bsr_dmat3'

! ... read target and channels information:

      Open(nut,file='target',status='OLD')
      Call R_target(nut)
      Call R_channels(nut)

      if(coupling.ne.'JK') then
       write(*,'(2a)') 'target coupling is ',coupling
       Stop 'bsr_d_jk: target must have coupling = JK'
      end if

      np=ntarg; Call Read_ipar(nut,'np',np)
      ni=ntarg; Call Read_ipar(nut,'ni',ni)

      allocate(TDL(ntarg*ntarg),TDV(ntarg*ntarg))
      TDL=0.d0; TDV=0.d0

      kpol = 1
      rank2 = 2*kpol

      ipri = 3
      open(ipri,file='bsr_d_jk_Aug2026_candidate.log')

      write(ipri,'(a)') 'bsr_d_jk'
      write(ipri,*)
      write(ipri,'(a)') &
       'The order of the rows and columns in the inner-region dipole matrices is reversed '// &
       'to match the RMI format expected by RMT.'
      write(ipri,'(a)') 'The outer-region coefficients AC, BLC and BVC are written without rescaling.'
      write(ipri,*)
      write(ipri,'(a)') repeat('=', 72)
      write(ipri,'(a)') 'Target'
      write(ipri,'(3(A6,1X),A10)') 'NELC', 'NZ', 'NTARG', 'COUPLING'
      write(ipri,'(3(I6,1X),A10)')  NELC, NZ, ntarg, coupling
      write(ipri,*)

!----------------------------------------------------------------------
!                      TARGET DIPOLE MATRIX ELEMENTS
!----------------------------------------------------------------------

! ... read asymptotic coefficients from H and recover target dipoles

      in=2
      Open(in,file='H',status='OLD',form='UNFORMATTED')

      read(in) h_nelc,h_nz,LRANG2,LAMAX,h_nast,RA,BSTO
      if(h_nelc.ne.NELC) Stop 'bsr_d_jk: H and target disagree on NELC'
      if(h_nz.ne.NZ) Stop 'bsr_d_jk: H and target disagree on NZ'
      if(h_nast.ne.ntarg) Stop 'bsr_d_jk: H and target disagree on NTARG'
      NAST=h_nast
      write(ipri,'(a,5(1x,i0),2(1x,f12.6))') 'H global:', &
           h_nelc,h_nz,LRANG2,LAMAX,h_nast,RA,BSTO
      read(in) (E,N=1,NAST)
      read(in) (L,N=1,NAST)
      read(in) (I,N=1,NAST)
      read(in) ((C,K=1,3),L=1,LRANG2)

      icount_h=0
   10 Continue

      icount_h=icount_h+1
      read(in,end=20) IL2, IS2, IP2, NCHAN, NHM, MORE
      IP2 = (-1)**IP2

      klsp = 0
      Do i=1,nlsp
       if(IL2.ne.lpar(i)) Cycle
       if(IS2.ne.ispar(i)) Cycle
       if(IP2.ne.ipar(i)) Cycle
       klsp=i
       Exit
      End do

      if(klsp.eq.0) Stop 'bsr_d_jk: unknown partial wave in H'
      if(nch(klsp).ne.nchan) Stop 'bsr_d_jk: nchan <> nch'

      read(in) (NCONAT, N=1,NAST)

      if(allocated(L2P)) Deallocate(L2P)
      Allocate(L2P(nchan))

!     As a check, the outer-electron orbital angular momentum in H in each
!     channel is confirmed to agree with the BSR target file. The K values are
!     read from the target file and then used to deduce the reduced dipole
!     matrix elements of the target by comparing with asymptotic coefficients
!     found in the H file.
      read(in) (L2P(i), I=1,NCHAN)
      if(any(L2P.ne.lch(klsp,1:nchan))) &
       Stop 'bsr_d_jk: H and target channel orders disagree'
      write(ipri,'(a,6(1x,i0))') 'H block matched:', &
           IL2,IS2,IP2,NCHAN,NHM,MORE
      write(ipri,'(a,1000(1x,i0))') '  L2P:',(L2P(i),i=1,NCHAN)
      write(ipri,'(a,1000(1x,i0))') '  target l:', &
           (lch(klsp,i),i=1,NCHAN)

      if(allocated(CF)) Deallocate(CF)
      Allocate(CF(nchan,nchan,lamax))
      read(in) (((CF(I,J,K), I=1,nchan), J=1,nchan), K=1,LAMAX)
      read(in) (E,i=1,NHM)
      read(in) ((W,i=1,nchan),j=1,NHM)

      eps = 1.D-6
      Call d_values_jk(nut,klsp,np,ni,ipri,eps,lamax,nchan,CF,TDL,TDV)

      if(MORE.gt.0) go to 10

   20 Continue
      Close(in)

!     The file fort.666 contains target dipole matrix elements, first length
!     and then velocity, obtained from the H file and is solely for internal
!     inspection.
      write(666,1112) TDL
      write(666,1112) TDV
      write(ipri,*)
      write(ipri,'(a)') 'Target dipole matrix elements written to fort.666'
  1112 FORMAT(10F8.3)

!----------------------------------------------------------------------
!                          DIPOLE MATRIX FILES
!----------------------------------------------------------------------

      klsp1=1
      klsp2=nlsp
      Call Read_iarg('klsp',klsp2)
      Call Read_iarg('klsp1',klsp1)
      Call Read_iarg('klsp2',klsp2)
      if(klsp1.lt.1) klsp1=1
      if(klsp2.gt.nlsp) klsp2=nlsp
      if(klsp2.lt.klsp1) Stop 'bsr_d_jk: klsp2 < klsp1'

      ipar0 = 1
      Call Read_iarg('ipar0',ipar0)
      if(abs(ipar0).ne.1) Stop 'bsr_d_jk: ipar0 must be +1 or -1'

      icount = 0
      write(ipri,*)
      write(ipri,'(a)') repeat('=', 72)
      write(ipri,'(a)') 'N+1 electron jK/BP transitions'
      write(ipri,'(a,2i5)') 'partial-wave range:', klsp1, klsp2
      write(ipri,'(a,i3)') 'initial-side parity:', ipar0
      write(ipri,'(a)') repeat('=', 72)
      write(ipri,*)

      open(81,status='SCRATCH',form='FORMATTED')

      Do i=klsp1,klsp2

       if(ipar(i).ne.ipar0) Cycle
       if(ispar(i).ne.0) Cycle

       write(BI,'(a,i3.3)') 'rsol.' ,i
       if(Icheck_file(BI).eq.0) Cycle
       write(BI,'(a,i3.3)') 'cfg.' ,i
       if(Icheck_file(BI).eq.0) Cycle

       Do j=klsp1,klsp2

        if(ispar(j).ne.0) Cycle
        if(ipar(i).eq.ipar(j)) Cycle

        write(BJ,'(a,i3.3)') 'rsol.' ,j
        if(Icheck_file(BJ).eq.0) Cycle
        write(BJ,'(a,i3.3)') 'cfg.' ,j
        if(Icheck_file(BJ).eq.0) Cycle

!       Electric dipole transitions connect states/blocks of opposite parity,
!       whose total angular momenta J are either equal (0->0 forbidden) or
!       differ by 1. The BSR target file labels 2J for each block.
        if(ITRA(lpar(i),rank2,lpar(j)).eq.0) Cycle
        if(lpar(i)+lpar(j).lt.rank2) Cycle

        write(ipri,'(a,1x,a,1x,a)') trim(BI), '<->', trim(BJ)
        write(ipri,'(i0,1x,i0,a,i0,1x,i0)') &
             lpar(i),ipar(i),' <-> ',lpar(j),ipar(j)

        write(AS,'(3(a,1x),a,2i3.3)') trim(MULT_EXE),trim(BJ),trim(BI), &
             'E1 mult_bnk_',i,j
        write(ipri,'(a)') trim(AS)
        Call System(AS)

        write(AS,'(a,a,2i3.3,a)') 'cp ','mult_bnk_',i,j,' mult_bnk'
        Call System(AS)

        icount = icount + 1
        write(FDD,'(a,i3.3)') 'D',icount
        write(FRAW,'(a,i3.3)') 'Djk_raw_',icount

        write(AS,'(a,1x,a,1x,a,1x,a,1x,a,2x,a,a)') &
             trim(DMAT_EXE),trim(BJ),trim(BI),'b','d','AF_dd=',trim(FRAW)
        write(ipri,'(a)') trim(AS)
        Call System(AS)

        Call Complete_D_file(trim(FRAW),trim(FDD),i,j,ipri)

        write(81,*) icount, ispar(j),lpar(j),(1-ipar(j))/2, &
                            ispar(i),lpar(i),(1-ipar(i))/2

       End do
      End do

!----------------------------------------------------------------------
!                                  D00
!----------------------------------------------------------------------
!     D00 is an unformatted file with symmetry-block information required by
!     RMT. D00.txt is a formatted version of this file. The first line is the
!     number of symmetry-block pairs and the following lines identify the
!     symmetry combinations that produce the dipole files D001, D002, etc., in
!     that order.
      open(82,file='D00',form='UNFORMATTED',status='REPLACE')
      open(123,file='D00.txt',form='FORMATTED',status='REPLACE')

      write(82) icount
      write(123,*) icount
      rewind(81)

      Do i = 1,icount
       read(81,*) i0,i1,i2,i3,i4,i5,i6
       write(82) i1,i2,i3,i4,i5,i6
       write(123,*) i1,i2,i3,i4,i5,i6
      End do

      Close(82)
      Close(123)
      Close(81,status='DELETE')

      write(ipri,*)
      write(ipri,'(a)') repeat('=', 72)
      write(ipri,'(a,i0)') 'total number of allowed transitions: ',icount
      write(ipri,'(a)') repeat('=', 72)
      close(ipri)

      End Program bsr_d_jk


!==========================================================================
      Subroutine d_values_jk(nut,klsp,np,ni,ipri,eps_acf,km,nchan,ACF,TDL,TDV)
!==========================================================================
!     Recover target dipoles from asymptotic coefficients for jK coupling.
!--------------------------------------------------------------------------
      Use zconst, only: c_au, time_au
      Use target
      Use channel

      Implicit none

      Integer, intent(in) :: nut, klsp, np, ni, ipri, km, nchan
      Real(8), intent(in) :: eps_acf
      Real(8), intent(in) :: ACF(nchan,nchan,km)
      Real(8), intent(inout) :: TDL(ntarg*ntarg), TDV(ntarg*ntarg)

      Real(8) :: de(ntarg,ntarg)
      Real(8) :: DLT(ntarg,ntarg), DVT(ntarg,ntarg)
      Integer :: IP(ntarg,ntarg)
      Real(8) :: S,SS
      Real(8), external :: Reduce_factor_jk
      Integer :: i,j,i1,i2,nt

      Call R_channel(nut,klsp)

      IP=0
      DLT=0.d0
      DVT=0.d0
      de=0.d0

      Do i=1,nch-1
       Do j=i+1,nch
        S=ACF(i,j,1)/2.d0
        i1=iptar(i)
        i2=iptar(j)
        if(abs(S).lt.eps_acf) Cycle
        if(i1.gt.ni.and.i2.gt.np) Cycle

        SS = Reduce_factor_jk(i,j,1,jkch(i),jkch(j))
        if(abs(SS).lt.eps_acf) Cycle

        S = S / SS
        DLT(i1,i2) = DLT(i1,i2) + S
        DLT(i2,i1) = DLT(i2,i1) + S
        de(i2,i1)=Etarg(i2)-Etarg(i1)
        IP(i1,i2) = IP(i1,i2) + 1
       End do
      End do

      nt = 0
      Do i1=1,ntarg
       Do i2=i1,ntarg
        if(IP(i1,i2).eq.0) Cycle
        DLT(i1,i2) = DLT(i1,i2) / IP(i1,i2)
        DLT(i2,i1) = DLT(i2,i1) / IP(i1,i2)
        nt = nt + 1
        DVT(i1,i2) = DLT(i1,i2)*de(i2,i1)
       End do
      End do

      if(nt.gt.0) &
       write(ipri,'(/a,i0)') 'Target dipole elements found in partial wave no. ', klsp
      write(ipri,'(/2a5,2a15,5x,a/)') 'idx1', 'idx2', 'length form', &
           'velocity form', 'states involved'

      Do i=1,ntarg-1
       Do j=i+1,ntarg
        if(DLT(i,j).eq.0.d0) Cycle
        write(ipri,'(2i5,E15.5,E15.5,5x,3a)') &
             i,j,DLT(i,j),DVT(i,j),trim(BFT(i)),' <-> ',trim(BFT(j))
        TDL((j-1)*ntarg+i)=DLT(i,j)
        TDV((j-1)*ntarg+i)=DVT(i,j)
        TDL((i-1)*ntarg+j)=DLT(i,j)
        TDV((i-1)*ntarg+j)=-DVT(i,j)
       End do
      End do

      write(ipri,*)
      write(ipri,*)'------------------------------------------------------------------------'

      End Subroutine d_values_jk


!======================================================================
      Real(8) Function Reduce_factor_jk(ich,jch,k,kchi,kchj)
!======================================================================
!     Factor connecting the reduced target dipole matrix element with the
!     asymptotic coefficient for a jK-coupled channel pair.
!----------------------------------------------------------------------
      Use target
      Use channel

      Implicit none

      Integer, intent(in) :: ich,jch,k,kchi,kchj
      Integer :: ll1,ll2,jj1,jj2,it,jt,J1,J2,JJ,ip,jp,kz
      Real(8) :: S, zero = 0.d0
      Real(8), external :: ZCLKL, Z_6j

      Reduce_factor_jk = zero

      ll1 = lch(ich)
      ll2 = lch(jch)
      S = ZCLKL(ll1,k,ll2)
      if(S.eq.zero) Return

      jj1 = kchi
      jj2 = kchj
      if(jj1.ne.jj2) Return

      it = iptar(ich)
      jt = iptar(jch)
      J1 = jtarg(it)
      J2 = jtarg(jt)

      ip = iptarg(it)
      jp = iptarg(jt)
      kz = 0
      if(ip.ne.jp) kz=1
      kz = kz - k
      if(MOD(kz,2).ne.0) Return

      JJ = jpar
      S = S * Z_6j(ll2+ll2+1,ll1+ll1+1,k+k+1,J1,J2,jj1)
      kz = J2+JJ+JJ-ll1-ll1-jj1+1
      kz = kz/2
      S = S * (-1) ** kz

      Reduce_factor_jk = S

      End Function Reduce_factor_jk


!======================================================================
      Subroutine Complete_D_file(AF_raw,AF_final,ilsp_row,ilsp_col,ipri)
!======================================================================
!     For each successive transition between symmetry blocks, bsr_dmat3
!     produces preliminary files Djk_raw_001, Djk_raw_002, etc. These names
!     avoid confusion with the D001, D002, etc. files used by RMT. The
!     Complete_D_file routine in bsr_d_jk.f90 converts the preliminary files to
!     the RMT input files D001, D002, etc.
!----------------------------------------------------------------------
      Use channels, only: nch,lch,lpar,ipar,ispar

      Implicit none

      Character(*), intent(in) :: AF_raw, AF_final
      Integer, intent(in) :: ilsp_row,ilsp_col,ipri
      Integer :: in, out
      Integer :: noterm,nrow,nchan_row,jrow,prow,srow,ncol,nchan_col,jcol
      Integer :: n1,n2,m1,m2,nval,i,j,idx,maxm1,nclean,span
      Integer :: mcount,ncount,pos
      Integer :: ac_nz,blc_nz,bvc_nz
      Integer :: prow_expected,prow_out
      Real(8) :: buttle1,buttle2,max_removed
      Real(8) :: ac_max,blc_max,bvc_max,ac_rms,blc_rms,bvc_rms
      Real(8), allocatable :: buf(:), outer(:),cgc(:)
      Real(8), allocatable :: dlen(:,:),dvel(:,:)

      in = 131
      out = 132
      open(in,file=AF_raw,form='UNFORMATTED',status='OLD')
      open(out,file=AF_final,form='UNFORMATTED',status='REPLACE')

      read(in) noterm,nrow,nchan_row,jrow,prow,srow,ncol,nchan_col,jcol
!     In the header of the dipole file, bsr_dmat3 writes the parity of the
!     block, corresponding to the rows in the file/matrix as 0 for even and −1
!     for odd. This value is crosschecked against the BSR target file. The
!     header for RMT writes 0 for even and +1 for odd, as expected.
      prow_expected=(ipar(ilsp_row)-1)/2
      prow_out=(1-ipar(ilsp_row))/2
      if(noterm.le.0 .or. nrow.le.0 .or. ncol.le.0) &
       Stop 'bsr_d_jk: invalid D matrix dimensions'
!     We now check that both the number of channels and 2J value in header of
!     the dipole file agree with the BSR target file. If the check fails, the
!     routine stops.
      if(nchan_row.ne.nch(ilsp_row)) &
       Stop 'bsr_d_jk: D row-channel count disagrees with target'
      if(nchan_col.ne.nch(ilsp_col)) &
       Stop 'bsr_d_jk: D column-channel count disagrees with target'
      if(jrow.ne.lpar(ilsp_row) .or. jcol.ne.lpar(ilsp_col)) &
       Stop 'bsr_d_jk: D angular labels disagree with target'
      if(prow.ne.prow_expected .or. srow.ne.ispar(ilsp_row)) &
       Stop 'bsr_d_jk: raw D row symmetry disagrees with target'
      write(out) noterm,nrow,nchan_row,jrow,prow_out,srow,ncol,nchan_col,jcol
      write(ipri,'(a,1x,a,1x,a)') 'D-file diagnostic:', &
           trim(AF_final),trim(AF_raw)
      write(ipri,'(a,9(1x,i0))') '  header written:',noterm,nrow,nchan_row, &
           jrow,prow_out,srow,ncol,nchan_col,jcol
      write(ipri,'(a,2(1x,i0))') '  row parity raw/written:',prow,prow_out

      allocate(dlen(nrow,ncol),dvel(nrow,ncol))
      dlen=0.d0
      dvel=0.d0

!     The rows and columns label the R-matrix eigenstates of the two symmetry
!     blocks. Each entry is the dipole matrix element between the corresponding
!     states. The BSR program bsr_dmat3 writes these matrices in order of
!     increasing energy within each block. The order of both the rows and the
!     columns is reversed intentionally here to match the form expected by
!     RMT’s RMI reader.
      n2 = 0
      Do while(n2.lt.ncol)
       n1 = n2 + 1
       n2 = min(n2+noterm,ncol)
       m2 = 0
       Do while(m2.lt.nrow)
        m1 = m2 + 1
        m2 = min(m2+noterm,nrow)
        mcount = m2-m1+1
        ncount = n2-n1+1
        nval = 2 * mcount * ncount
        allocate(buf(nval))
        read(in) buf
        pos=0
        Do j=n1,n2
         Do i=m1,m2
          pos=pos+1
          dlen(i,j)=buf(pos)
         End do
        End do
        Do j=n1,n2
         Do i=m1,m2
          pos=pos+1
          dvel(i,j)=buf(pos)
         End do
        End do
        deallocate(buf)
       End do
      End do

      n2 = 0
      Do while(n2.lt.ncol)
       n1 = n2 + 1
       n2 = min(n2+noterm,ncol)
       m2 = 0
       Do while(m2.lt.nrow)
        m1 = m2 + 1
        m2 = min(m2+noterm,nrow)
        mcount = m2-m1+1
        ncount = n2-n1+1
        nval = 2 * mcount * ncount
        allocate(buf(nval))
        pos=0
        Do j=n1,n2
         Do i=m1,m2
          pos=pos+1
          buf(pos)=dlen(nrow+1-i,ncol+1-j)
         End do
        End do
        Do j=n1,n2
         Do i=m1,m2
          pos=pos+1
          buf(pos)=dvel(nrow+1-i,ncol+1-j)
         End do
        End do
        write(out) buf
        deallocate(buf)
       End do
      End do

      write(ipri,'(a,4(1x,es14.6))') &
       '  length samples raw(1,1), raw(end,end), written(1,1), written(end,end):', &
       dlen(1,1),dlen(nrow,ncol),dlen(nrow,ncol),dlen(1,1)

!     In the version of bsr_dmat3 used here, following the inner-region dipole
!     matrices, two Buttle correction records and one Clebsch–Gordan
!     coefficient record are written. RMT expects three Buttle correction
!     records. Thus, we write the two records from BSR (all zero) and add a
!     third (empty) record before writing the Clebsch–Gordan coefficients. This
!     ensures that the outer-region coefficients are where RMT expects them to
!     be.
      read(in) buttle1
      read(in) buttle2
      read(in) maxm1
      if(maxm1.lt.0) Stop 'bsr_d_jk: invalid CGC record'
      allocate(cgc(maxm1))
      if(maxm1.gt.0) then
       backspace(in)
       read(in) maxm1,cgc
      end if

      nval = 3*nchan_row*nchan_col
      allocate(outer(nval))
      read(in) outer
      span = nchan_row*nchan_col
      ac_nz = count(abs(outer(1:span)).gt.1.d-12)
      blc_nz = count(abs(outer(span+1:2*span)).gt.1.d-12)
      bvc_nz = count(abs(outer(2*span+1:3*span)).gt.1.d-12)
      ac_max = maxval(abs(outer(1:span)))
      blc_max = maxval(abs(outer(span+1:2*span)))
      bvc_max = maxval(abs(outer(2*span+1:3*span)))
      ac_rms = sqrt(sum(outer(1:span)**2)/real(span,8))
      blc_rms = sqrt(sum(outer(span+1:2*span)**2)/real(span,8))
      bvc_rms = sqrt(sum(outer(2*span+1:3*span)**2)/real(span,8))
      write(ipri,'(a,3(1x,i0))') &
       'Number of AC, BLC and BVC entries of absolute magnitude greater than 1.d-12 '// &
       'prior to the application of the AC selection rule:', &
           ac_nz,blc_nz,bvc_nz
      write(ipri,'(a,3(1x,es14.6))') '  outer maxabs AC/BLC/BVC:', &
           ac_max,blc_max,bvc_max
      write(ipri,'(a,3(1x,es14.6))') '  outer rms AC/BLC/BVC:', &
           ac_rms,blc_rms,bvc_rms

!     AC is the outer electron's dipole coefficient. The outer-electron orbital
!     angular momenta of the two channels must differ by one. All AC values
!     forbidden by this rule are set to 0. BLC and BVC are the length and
!     velocity dipole coefficients for the residual target ion, which are
!     copied directly from BSR.
      nclean=0; max_removed=0.d0
      Do j=1,nchan_col
       Do i=1,nchan_row
        if(abs(lch(ilsp_row,i)-lch(ilsp_col,j)).eq.1) Cycle
!       bsr_dmat3 first writes all the column entries for one row before moving
!       on. The AC coefficient for row i and column j is therefore found in
!       position (i-1)*nchan_col+j.
        idx=(i-1)*nchan_col+j
        if(outer(idx).ne.0.d0) then
         nclean=nclean+1
         max_removed=max(max_removed,abs(outer(idx)))
         outer(idx)=0.d0
        end if
       End do
      End do

      write(out) buttle1
      write(out) buttle2
      write(out)
      write(out) maxm1,cgc
      write(out) outer

      write(ipri,'(a,i0,a,es12.4)') &
       'Number of initially nonzero AC values set to 0 by selection rule: ',nclean, &
       ', largest absolute value prior to zeroing: ',max_removed
      write(ipri,*)

      deallocate(outer,cgc,dlen,dvel)
      close(in)
      close(out)

      End Subroutine Complete_D_file
